test("matching settings survive reopen and require explicit clearing after capability loss", async ({ context, page, request }) => {
  await context.addCookies([{ name: "case_test_session", value: "fixture-workflow", domain: "127.0.0.1", path: "/" }]);
  await page.goto(`/detection/${scenario}/screening`);
  await page.getByRole("button", { name: "Create screening configuration" }).click();
  const form = page.getByRole("form");
  await form.getByLabel("Name", { exact: true }).fill("Matching policy");
  await form.getByLabel("Name field", { exact: true }).selectOption("beneficiary_name");
  await form.getByLabel("Review inbox").selectOption("22222222-2222-4222-8222-222222222222");
  await form.getByLabel("Require an additional condition").check();
  await form.getByLabel("Recognize names in the input").check();
  await form.getByLabel("Ignore list (optional)").selectOption("77777777-7777-4777-8777-777777777777");
  await form.getByLabel("Minimum name length").fill("5");
  await form.getByLabel("Remove digits from the name").check();
  await form.getByLabel(/Match threshold/).fill("0");
  await form.getByLabel(/Result limit/).fill("50");
  await form.getByLabel(/Dataset IDs/).fill("synthetic,other-test");
  await form.getByRole("button", { name: "Save configuration" }).click();
  await expect(page.getByRole("status")).toContainText("saved");
  await page.reload();
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await expect(form.getByLabel("Require an additional condition")).toBeChecked();
  await expect(form.getByLabel("Recognize names in the input")).toBeChecked();
  await expect(form.getByLabel("Ignore list (optional)")).toHaveValue("77777777-7777-4777-8777-777777777777");
  await expect(form.getByLabel("Minimum name length")).toHaveValue("5");
  await expect(form.getByLabel("Remove digits from the name")).toBeChecked();
  await expect(form.getByLabel(/Match threshold/)).toHaveValue("0");
  await expect(form.getByLabel(/Result limit/)).toHaveValue("50");
  await expect(form.getByLabel(/Dataset IDs/)).toHaveValue("synthetic,other-test");
  await form.getByLabel(/Result limit/).fill("51");
  await form.getByRole("button", { name: "Save configuration" }).click();
  await expect(form).toBeVisible();
  expect(await form.getByLabel(/Result limit/).evaluate((el: HTMLInputElement) => el.validity.rangeOverflow)).toBeTruthy();
  await request.get("http://127.0.0.1:3199/fixture/scenario-address-unavailable");
  await page.reload();
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await expect(form.getByRole("button", { name: "Save configuration" })).toBeDisabled();
  await form.getByLabel("Recognize names in the input").click();
  await expect(form.getByLabel("Recognize names in the input")).toHaveCount(0);
  for (const label of [/Match threshold/, /Result limit/, /Dataset IDs/]) await form.getByLabel(label).fill("");
  await form.getByRole("button", { name: "Save configuration" }).click();
  await expect(page.getByRole("status")).toContainText("saved");
});
