test("matching settings survive reopen and require explicit clearing after capability loss", async ({ context, page, request }) => {
  await context.addCookies([{ name: "case_test_session", value: "fixture-workflow", domain: "127.0.0.1", path: "/" }]);
  await page.goto(`/detection/${scenario}/screening`);
  await page.getByRole("button", { name: "Add screening" }).click();
  const form = page.getByRole("form");
  await form.getByText("More identity details", {exact:true}).click();
  await form.getByLabel("Rule name", { exact: true }).fill("Matching policy");
  await form.getByLabel("Name to check", { exact: true }).selectOption("beneficiary_name");
  await form.getByLabel("Review inbox").selectOption("22222222-2222-4222-8222-222222222222");
  await form.getByText("Only screen certain records",{exact:true}).click();
  await form.getByLabel("Add a condition").check();
  await form.getByText("Advanced settings",{exact:true}).click();
  await form.getByLabel("Extract names from text").check();
  await form.getByLabel("Words to ignore").selectOption("77777777-7777-4777-8777-777777777777");
  await form.getByLabel("Minimum name length").fill("5");
  await form.getByLabel("Remove numbers from names").check();
  await form.getByLabel(/Minimum similarity/).fill("0");
  await form.getByLabel(/Maximum matches/).fill("50");
  await form.getByLabel(/Source datasets/).fill("synthetic,other-test");
  await form.getByRole("button", { name: "Save screening" }).click();
  await expect(page.getByRole("status")).toContainText("saved");
  await page.reload();
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await expect(form.getByLabel("Add a condition")).toBeChecked();
  await form.getByText("Advanced settings", {exact:true}).click();
  await expect(form.getByLabel("Extract names from text")).toBeChecked();
  await expect(form.getByLabel("Words to ignore")).toHaveValue("77777777-7777-4777-8777-777777777777");
  await expect(form.getByLabel("Minimum name length")).toHaveValue("5");
  await expect(form.getByLabel("Remove numbers from names")).toBeChecked();
  await expect(form.getByLabel(/Minimum similarity/)).toHaveValue("0");
  await expect(form.getByLabel(/Maximum matches/)).toHaveValue("50");
  await expect(form.getByLabel(/Source datasets/)).toHaveValue("synthetic,other-test");
  await form.getByLabel(/Maximum matches/).fill("51");
  await form.getByRole("button", { name: "Save screening" }).click();
  await expect(form).toBeVisible();
  expect(await form.getByLabel(/Maximum matches/).evaluate((el: HTMLInputElement) => el.validity.rangeOverflow)).toBeTruthy();
  await request.get("http://127.0.0.1:3199/fixture/scenario-address-unavailable");
  await page.reload();
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await expect(form.getByRole("button", { name: "Save screening" })).toBeDisabled();
  await form.getByLabel("Extract names from text").click();
  await expect(form.getByLabel("Extract names from text")).toHaveCount(0);
  for (const label of [/Minimum similarity/, /Maximum matches/, /Source datasets/]) await form.getByLabel(label).fill("");
  await form.getByRole("button", { name: "Save screening" }).click();
  await expect(page.getByRole("status")).toContainText("saved");
});
