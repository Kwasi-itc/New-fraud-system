test("delete rejects stale versions and recovers after a lost acknowledgement", async ({ context, page, request }) => {
  await context.addCookies([{ name: "case_test_session", value: "fixture-workflow", domain: "127.0.0.1", path: "/" }]);
  const rule = { id: "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa", name: "Delete test", enabled: true, outcomes: [], condition: { kind: "always" }, action_type: "do_nothing", inbox_id: "", title: "", tag_ids: [], updated_at: null };
  const headers = { Origin: "http://127.0.0.1:3100" };
  const saved = await (await page.request.put(`${url}/rules/${rule.id}`, { headers, data: rule })).json();
  await page.goto(`/detection/${scenario}/workflow`);
  await expect(page.getByLabel("Rule name", { exact: true })).toHaveValue("Delete test");
  const changed = await (await page.request.put(`${url}/rules/${rule.id}`, { headers, data: { ...saved, name: "Concurrent edit" } })).json();
  page.on("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Delete", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Workflow changed" })).toBeVisible();
  await expect(page.getByLabel("Rule name", { exact: true })).toHaveValue("Concurrent edit");
  await request.get("http://127.0.0.1:3199/fixture/workflow-lost-ack");
  await page.getByRole("button", { name: "Delete", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Response lost" })).toBeVisible();
  await expect(page.getByRole("form")).toHaveCount(0);
  expect((await page.request.delete(`${url}/rules/${rule.id}`, { headers, data: changed })).status()).toBe(200);
});

