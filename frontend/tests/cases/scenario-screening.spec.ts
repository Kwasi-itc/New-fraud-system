import { expect, test } from "@playwright/test";
const scenario = "88888888-8888-4888-8888-888888888888";
test.beforeEach(async ({ request }) => { await request.get("http://127.0.0.1:3199/reset"); });
test("create, reopen and disable a mapped scenario screening configuration", async ({ context, page, request }) => {
  await context.addCookies([{ name: "case_test_session", value: "fixture-workflow", domain: "127.0.0.1", path: "/" }]);
  await page.goto(`/detection/${scenario}/screening`);
  await expect(page.getByText("No screening rules yet")).toBeVisible();
  await page.getByRole("button", { name: "Add screening" }).click();
  const form = page.getByRole("form", { name: "Screening configuration" });
  await form.getByText("More identity details", {exact:true}).click();
  await form.getByLabel("Rule name", { exact: true }).fill("Beneficiary screening");
  await form.getByLabel("Name to check", { exact: true }).selectOption("beneficiary_name");
  await form.getByLabel("Address").selectOption("postal_address");
  await form.getByLabel("Date of birth").selectOption("birth_date");
  await form.getByLabel("Review inbox").selectOption("22222222-2222-4222-8222-222222222222");
  await form.getByRole("switch", {name:"Active"}).check();
  await form.getByRole("button", { name: "Save screening" }).click();
  await expect(page.getByRole("status")).toContainText("saved");
  await page.reload();
  await expect(page.getByText("Person · beneficiary_name")).toBeVisible();
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await expect(form.getByLabel("Address")).toHaveValue("postal_address");
  await expect(form.getByLabel("Date of birth")).toHaveValue("birth_date");
  await form.getByLabel("Screen for").selectOption("Organization");
  await expect(form.getByRole("alert")).toContainText("Clear its mapping");
  await expect(form.getByRole("button", { name: "Save screening" })).toBeDisabled();
  await form.getByLabel("Date of birth").selectOption("");
  await form.getByLabel("Name to check", { exact: true }).selectOption("company_name");
  await form.getByRole("switch", {name:"Active"}).uncheck();
  await form.getByRole("button", { name: "Save screening" }).click();
  await expect(page.getByText("Company · company_name")).toBeVisible();
  await expect(page.getByText(/After decision/)).toBeVisible();
  await request.get("http://127.0.0.1:3199/fixture/scenario-address-unavailable");
  await page.reload();
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await expect(form.getByLabel("Address")).toHaveValue("postal_address");
  await expect(form.getByRole("button", { name: "Save screening" })).toBeDisabled();
  await form.getByLabel("Address").selectOption("");
  await form.getByRole("button", { name: "Save screening" }).click();
  await expect(page.getByRole("status")).toContainText("saved");
});
test("conflict retains draft; invalid outcomes and unauthorized proxy are denied", async ({ context, page, request }) => {
  await context.addCookies([{ name: "case_test_session", value: "fixture-workflow", domain: "127.0.0.1", path: "/" }]);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`/detection/${scenario}/screening`);
  await page.getByRole("button", { name: "Add screening" }).click();
  const form = page.getByRole("form");
  await form.getByText("More identity details", {exact:true}).click();
  await form.getByLabel("Rule name", { exact: true }).fill("Draft");
  await form.getByLabel("Name to check", { exact: true }).selectOption("beneficiary_name");
  await form.getByLabel("Review inbox").selectOption("22222222-2222-4222-8222-222222222222");
  await form.getByLabel("Review", { exact: true }).uncheck();
  await expect(form.getByRole("button", { name: "Save screening" })).toBeDisabled();
  await form.getByLabel("Review", { exact: true }).check();
  await request.get("http://127.0.0.1:3199/fixture/scenario-screening-conflict");
  await form.getByRole("button", { name: "Save screening" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Configuration changed" })).toBeVisible();
  await expect(form.getByLabel("Rule name", { exact: true })).toHaveValue("Draft");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  const foreignOrigin = await page.request.put(`/api/scenario-screening/scenarios/${scenario}/configs/${scenario}`, { headers: { origin: "https://foreign.invalid" }, data: {} });
  expect(foreignOrigin.status()).toBe(403);
  await context.clearCookies();
  const denied = await page.request.get(`/api/scenario-screening/scenarios/${scenario}`);
  expect(denied.status()).toBe(401);
});

