test("create, reopen and disable a mapped scenario screening configuration", async ({ context, page, request }) => {
  await context.addCookies([{ name: "case_test_session", value: "fixture-workflow", domain: "127.0.0.1", path: "/" }]);
  await page.goto(`/detection/${scenario}/screening`);
  await expect(page.getByText("No editable screening configurations yet.")).toBeVisible();
  await page.getByRole("button", { name: "Create screening configuration" }).click();
  const form = page.getByRole("form", { name: "Screening configuration" });
  await form.getByLabel("Name", { exact: true }).fill("Beneficiary screening");
  await form.getByLabel("Name field", { exact: true }).selectOption("beneficiary_name");
  await form.getByLabel("Address field (optional)").selectOption("postal_address");
  await form.getByLabel("Birth-date field (optional)").selectOption("birth_date");
  await form.getByLabel("Review inbox").selectOption("22222222-2222-4222-8222-222222222222");
  await form.getByLabel("Enable for future decisions").check();
  await form.getByRole("button", { name: "Save configuration" }).click();
  await expect(page.getByRole("status")).toContainText("saved");
  await page.reload();
  await expect(page.getByText("Person · beneficiary_name · Enabled")).toBeVisible();
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await expect(form.getByLabel("Address field (optional)")).toHaveValue("postal_address");
  await expect(form.getByLabel("Birth-date field (optional)")).toHaveValue("birth_date");
  await form.getByLabel("Entity type").selectOption("Organization");
  await expect(form.getByRole("alert")).toContainText("Clear its mapping");
  await expect(form.getByRole("button", { name: "Save configuration" })).toBeDisabled();
  await form.getByLabel("Birth-date field (optional)").selectOption("");
  await form.getByLabel("Name field", { exact: true }).selectOption("company_name");
  await form.getByLabel("Enable for future decisions").uncheck();
  await form.getByRole("button", { name: "Save configuration" }).click();
  await expect(page.getByText("Organization · company_name · Disabled")).toBeVisible();
  await expect(page.getByText(/does not recalculate the original decision score/)).toBeVisible();
  await request.get("http://127.0.0.1:3199/fixture/scenario-address-unavailable");
  await page.reload();
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await expect(form.getByLabel("Address field (optional)")).toHaveValue("postal_address");
  await expect(form.getByRole("button", { name: "Save configuration" })).toBeDisabled();
  await form.getByLabel("Address field (optional)").selectOption("");
  await form.getByRole("button", { name: "Save configuration" }).click();
  await expect(page.getByRole("status")).toContainText("saved");
});
test("conflict retains draft; invalid outcomes and unauthorized proxy are denied", async ({ context, page, request }) => {
  await context.addCookies([{ name: "case_test_session", value: "fixture-workflow", domain: "127.0.0.1", path: "/" }]);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`/detection/${scenario}/screening`);
  await page.getByRole("button", { name: "Create screening configuration" }).click();
  const form = page.getByRole("form");
  await form.getByLabel("Name", { exact: true }).fill("Draft");
  await form.getByLabel("Name field", { exact: true }).selectOption("beneficiary_name");
  await form.getByLabel("Review inbox").selectOption("22222222-2222-4222-8222-222222222222");
  await form.getByLabel("Review", { exact: true }).uncheck();
  await expect(form.getByRole("button", { name: "Save configuration" })).toBeDisabled();
  await form.getByLabel("Review", { exact: true }).check();
  await request.get("http://127.0.0.1:3199/fixture/scenario-screening-conflict");
  await form.getByRole("button", { name: "Save configuration" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Configuration changed" })).toBeVisible();
  await expect(form.getByLabel("Name", { exact: true })).toHaveValue("Draft");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  const foreignOrigin = await page.request.put(`/api/scenario-screening/scenarios/${scenario}/configs/${scenario}`, { headers: { origin: "https://foreign.invalid" }, data: {} });
  expect(foreignOrigin.status()).toBe(403);
  await context.clearCookies();
  const denied = await page.request.get(`/api/scenario-screening/scenarios/${scenario}`);
  expect(denied.status()).toBe(401);
});

