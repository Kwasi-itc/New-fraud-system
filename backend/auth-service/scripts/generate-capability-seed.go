//go:build ignore

// Generate the auth-owned SQL seed from the shared catalog and explicit bundles.
// Run from backend/platform-auth:
// go run ../auth-service/scripts/generate-capability-seed.go > ../auth-service/internal/platform/schema_v5_seed.sql
package main
import(
 "fmt"
 "sort"
 "strings"
 auth "github.com/Kwasi-itc/New-fraud-system/backend/platform-auth"
)
func quote(s string)string{return "'"+strings.ReplaceAll(s,"'","''")+"'"}
func array(values []string)string{out:=make([]string,len(values));for i,v:=range values{out[i]=quote(v)};return "ARRAY["+strings.Join(out,",")+"]::text[]"}
func main(){
 fmt.Println("-- Generated by auth-service/scripts/generate-capability-seed.go; do not hand edit.")
 for _,c:=range auth.Catalog(){
  fmt.Printf("INSERT INTO identity.capability_catalog(name,human,service,client_access,reserved) VALUES(%s,%t,%t,%s,%t) ON CONFLICT(name) DO UPDATE SET human=excluded.human,service=excluded.service,client_access=excluded.client_access,reserved=excluded.reserved;\n",quote(c.Name),c.Human,c.Service,quote(c.Client),c.Reserved)
 }
 names:=map[string]string{"tenant_admin":"Tenant Administrator","case_manager_admin":"Case Administrator","case_investigator":"Investigator","platform_viewer":"Platform Viewer","platform_builder":"Platform Builder","platform_publisher":"Platform Publisher","platform_admin":"Platform Administrator"}
 roles:=auth.PredefinedRoles();ids:=make([]string,0,len(roles));for id:=range roles{ids=append(ids,id)};sort.Strings(ids)
 for _,id:=range ids{fmt.Printf("INSERT INTO identity.predefined_roles(id,name,capabilities) VALUES(%s,%s,%s) ON CONFLICT(id) DO UPDATE SET name=excluded.name,capabilities=excluded.capabilities;\n",quote(id),quote(names[id]),array(roles[id]))}
 fmt.Println(`INSERT INTO identity.roles(tenant_id,id,name,builtin,capabilities)
 SELECT t.id,r.id,r.name,true,r.capabilities FROM core.tenants t CROSS JOIN identity.predefined_roles r
 ON CONFLICT(tenant_id,id) DO UPDATE SET capabilities=excluded.capabilities,version=identity.roles.version+1
 WHERE identity.roles.builtin AND identity.roles.capabilities IS DISTINCT FROM excluded.capabilities;
 INSERT INTO identity.member_roles(tenant_id,user_id,role_id)
 SELECT tenant_id,user_id,unnest(roles) FROM identity.memberships ON CONFLICT DO NOTHING;
 INSERT INTO identity.invitation_roles(tenant_id,invitation_id,role_id)
 SELECT tenant_id,id,unnest(roles) FROM identity.invitations WHERE status='pending' ON CONFLICT DO NOTHING;`)
}
