// Read-only browser acceptance against the retained local NovaPay demonstration.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {localOrigin} from './mysql-origin.mjs';

const root=fileURLToPath(new URL('../../',import.meta.url));
const local=resolve(root,'.local/mysql-dev/novapay-demo');
const login=JSON.parse(readFileSync(resolve(local,'login.json'),'utf8'));
const state=JSON.parse(readFileSync(resolve(local,'state.json'),'utf8'));
assert.equal(login.temporary,false,'Complete the local demo setup first.');
const scenario=state.scenarios.screening;
const origin=localOrigin(process.env.FRAUD_APP_ORIGIN||'http://localhost:'+(process.env.MYSQL_GATEWAY_PORT||8088));
const output=resolve(root,'frontend/evidence/novapay-demo/rules-list');
mkdirSync(output,{recursive:true});
const require=createRequire(resolve(root,'frontend/package.json'));
const {chromium}=require('@playwright/test');
const browser=await chromium.launch({headless:true});
const context=await browser.newContext();
const page=await context.newPage();
page.setDefaultTimeout(30000);
const traffic=[];
page.on('request',request=>{if(request.url().includes('/api/scenario-screening/'))traffic.push({method:request.method(),path:new URL(request.url()).pathname});});
try {
 await page.goto(origin+'/login');
 await page.getByRole('button',{name:'Continue to sign in'}).click();
 await page.locator('#username').fill(login.username);
 await page.locator('#password').fill(login.password);
 await page.locator('#kc-login').click();
 await page.waitForURL(origin+'/my-account');
 const response=await context.request.get(origin+'/api/scenario-screening/scenarios/'+scenario.id);
 assert.equal(response.status(),200);
 const configuration=await response.json();
 assert.equal(configuration.tenant_id,state.tenant);
 assert.equal(configuration.rules.length,2);
 const scoreResponse=await context.request.get(origin+`/api/decisions/tenants/${state.tenant}/scenarios/${scenario.id}/iterations/${scenario.iteration}/rules`);
 assert.equal(scoreResponse.status(),200);
 const scores=(await scoreResponse.json()).rules;
 const url=origin+`/detection/${scenario.id}/edit?tab=Rules&iterationId=${scenario.iteration}`;
 await page.goto(url);
 const table=page.getByRole('table',{name:'Scenario rules'});
 await table.waitFor();
 await page.waitForLoadState('networkidle');
 assert.equal(await table.getByRole('row').count(),1+scores.length+configuration.rules.length);
 for(const rule of configuration.rules){const row=table.getByRole('row').filter({has:page.getByRole('link',{name:rule.name,exact:true})});assert.equal(await row.count(),1);assert.ok((await row.innerText()).includes('Screening'));assert.ok((await row.innerText()).includes('No score change'));}
 await page.screenshot({path:resolve(output,'combined-rules-desktop.png'),fullPage:true});
 await page.getByLabel('Rule type').selectOption('screening');
 assert.equal(await table.getByRole('row').count(),1+configuration.rules.length);
 const selected=configuration.rules.find(rule=>rule.entity_type==='Person');
 assert.ok(selected);
 await table.getByRole('row').filter({has:page.getByRole('link',{name:selected.name,exact:true})}).getByRole('link',{name:'Edit',exact:true}).click();
 await page.waitForURL(origin+`/detection/${scenario.id}/screening?configId=${selected.id}`);
 const form=page.getByRole('form',{name:'Screening configuration'});
 await form.waitFor();
 assert.equal(await form.getByLabel('Name',{exact:true}).inputValue(),selected.name);
 assert.equal(await form.getByLabel('Name field',{exact:true}).inputValue(),selected.name_field);
 assert.equal(await form.getByLabel('Match threshold (0-100)').inputValue(),String(selected.threshold));
 await page.screenshot({path:resolve(output,'selected-screening-editor.png'),fullPage:true});
 await page.goto(url);
 await page.setViewportSize({width:390,height:844});
 await table.waitFor();
 await page.getByLabel('Rule type').selectOption('screening');
 await page.screenshot({path:resolve(output,'screening-rules-mobile.png'),fullPage:true});
 assert.ok(traffic.every(request=>request.method==='GET'),'Read-only acceptance must not mutate screening settings.');
 const report={at:new Date().toISOString(),passed:true,tenant:state.tenant,scenario:scenario.id,scoreRows:scores.length,screeningRows:configuration.rules.length,screeningRequests:traffic,desktopAndMobile:true,directEditorVerified:true,url};
 writeFileSync(resolve(output,'report.json'),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report,null,2));
} finally {await context.close();await browser.close();}
