func verifyTextConstraintRecovery(t *testing.T, ctx context.Context, db *sql.DB, database string, tenantID, tableID uuid.UUID, name string, field datamodel.Field, mapped []store.MappedPhysicalField, previous store.PhysicalDDLPlan, shared *installation.ExactKeyReadiness, policies []store.PhysicalAccessPolicy, scenario string) {
	t.Helper()
	if !strings.HasPrefix(database, "data_model_metadata_test_") {
		t.Fatal("disposable generated fixture required")
	}
	schema, _ := mysqlstore.Identifier(database)
	qt := schema + ".`" + name + "`"
	column := ""
	for _, m := range mapped {
		if m.Field.ID == field.ID {
			column = m.Components[0].Name
		}
	}
	quoted := "`" + column + "`"
	exec := func(q string, args ...any) {
		t.Helper()
		if _, err := db.ExecContext(ctx, q, args...); err != nil {
			t.Fatal(err)
		}
	}
	apply := func(enable bool, fault string) store.PhysicalDDLPlan {
		t.Helper()
		planner, err := store.NewPhysicalPlanner(database, tenantID, store.PhysicalTable{TableID: tableID, Name: name}, mapped)
		if err != nil {
			t.Fatal(err)
		}
		var statements []store.PhysicalStatement
		if enable {
			statements, err = planner.EnableTextUnique(field.ID, previous.Creation.Definer)
		} else {
			statements, err = planner.DisableTextUnique(field.ID, previous.Creation.Definer)
		}
		if err != nil {
			t.Fatal(err)
		}
		// This database is generated by metadataDB. Reset only this fixture table
		// to capture empty reference definitions, then restore and seed test records.
		reset := func() {
			exec("DROP TABLE " + qt)
			var definition map[string]string
			if err := json.Unmarshal([]byte(previous.FinalTableDefinition()), &definition); err != nil {
				t.Fatal(err)
			}
			exec(definition["Create Table"])
			for _, guard := range previous.ActiveGuards() {
				exec(guard.SQL)
			}
		}
		reset()
		conn, err := db.Conn(ctx)
		if err != nil {
			t.Fatal(err)
		}
		var refs []migrations.Step
		for _, s := range statements {
			step := s.ReferenceStep()
			step.Before, err = migrations.Definition(ctx, conn, database, step.Kind, step.Name)
			if err != nil {
				t.Fatal(err)
			}
			if _, err = conn.ExecContext(ctx, step.SQL); err != nil {
				t.Fatal(err)
			}
			step.After, err = migrations.Definition(ctx, conn, database, step.Kind, step.Name)
			if err != nil {
				t.Fatal(err)
			}
			refs = append(refs, step)
		}
		if err = conn.Close(); err != nil {
			t.Fatal(err)
		}
		plan, err := planner.BindRecordChanges(previous, statements, refs)
		if err != nil {
			t.Fatal(err)
		}
		reset()
		var values []string
		var args []any
		at := time.Now().UTC().Truncate(time.Microsecond)
		for i := 0; i < 302; i++ {
			var value any = fmt.Sprintf("value-%d", i)
			if i >= 300 {
				value = nil
			}
			values = append(values, "(?,?,?,?)")
			args = append(args, mysqlstore.UUID(uuid.New()), fmt.Sprintf("record-%d", i), at, value)
		}
		exec("INSERT INTO "+qt+"(id,`"+previous.Creation.ObjectColumn+"`,`"+previous.Creation.UpdatedColumn+"`,"+quoted+") VALUES "+strings.Join(values, ","), args...)
		var epoch int64
		var version mysqlstore.UUID
		if err := db.QueryRowContext(ctx, "SELECT epoch,published_version FROM "+schema+".data_model_physical_tables WHERE tenant_id=? AND table_id=?", mysqlstore.UUID(tenantID), mysqlstore.UUID(tableID)).Scan(&epoch, &version); err != nil {
			t.Fatal(err)
		}
		expected := uuid.UUID(version)
		operation := uuid.New()
		actor := uuid.NewString()
		hash := [32]byte{13}
		raw, err := json.Marshal(plan)
		if err != nil {
			t.Fatal(err)
		}
		intents, err := store.NewDDLIntentStore(db, database, tenantID, 1<<20)
		if err != nil {
			t.Fatal(err)
		}
		err = store.PreparePhysicalFieldChange(ctx, db, func(tx *sql.Tx) error {
			var id mysqlstore.UUID
			if err := tx.QueryRowContext(ctx, "SELECT id FROM "+schema+".data_model_tables WHERE tenant_id=? AND id=? FOR UPDATE", mysqlstore.UUID(tenantID), mysqlstore.UUID(tableID)).Scan(&id); err != nil {
				return err
			}
			if _, err := intents.PrepareTx(ctx, tx, store.DDLIntent{TableID: tableID, OperationID: operation, RequestHash: hash, ActorKind: "api", ActorID: actor, ExpectedEpoch: epoch, ExpectedVersion: &expected, Shape: raw}); err != nil {
				return err
			}
			if enable {
				return store.CheckTextDuplicates(ctx, tx, database, name, column)
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
		policy := installation.RecordInstallerPolicy{Principal: installation.Definer{User: "tp_" + strings.ReplaceAll(uuid.NewString(), "-", "")[:24], Host: "%"}, Table: name, NativeChanges: true, TextGuards: plan.InstallsTextGuards(), BackfillColumn: plan.TextBackfillColumn()}
		account, _ := policy.Principal.SQLAccount()
		exec("CREATE USER " + account + " IDENTIFIED BY 'isolated-text-only'")
		defer func() {
			if _, err := db.Exec("DROP USER " + account); err != nil {
				t.Error(err)
			}
		}()
		grants, err := policy.ActiveGrants(database)
		if err != nil {
			t.Fatal(err)
		}
		for _, grant := range grants {
			exec(grant)
		}
		login, err := mysqlstore.Open(ctx, mysqlstore.Config{Address: os.Getenv("DATA_MODEL_MYSQL_TEST_ADDRESS"), Database: database, User: policy.Principal.User, Password: "isolated-text-only", AllowInsecureTransport: true, MaxOpen: 1, MaxIdle: 1, ConnectTimeout: 5 * time.Second, ReadTimeout: 10 * time.Second, WriteTimeout: 10 * time.Second, ConnMaxLifetime: time.Minute, ConnMaxIdleTime: time.Minute})
		if err != nil {
			t.Fatal(err)
		}
		defer login.Close()
		executor, err := store.NewPhysicalExecutor(login, database, tenantID)
		if err != nil {
			t.Fatal(err)
		}
		foreign, err := store.NewPhysicalExecutor(login, database, uuid.New())
		if err != nil {
			t.Fatal(err)
		}
		if err := foreign.ExecuteSteps(ctx, tableID, operation); !errors.Is(err, sql.ErrNoRows) {
			t.Fatal("foreign tenant operation accepted", err)
		}
		waitReleased := func() {
			sum := sha256.Sum256([]byte(database + ":" + tenantID.String() + ":" + tableID.String()))
			lock := fmt.Sprintf("data_model_ddl_%x", sum[:24])
			conn, err := db.Conn(ctx)
			if err != nil {
				t.Fatal(err)
			}
			var got int
			if err = conn.QueryRowContext(ctx, "SELECT GET_LOCK(?,5)", lock).Scan(&got); err != nil || got != 1 {
				t.Fatal("old session not fenced", err)
			}
			if err = conn.QueryRowContext(ctx, "SELECT RELEASE_LOCK(?)", lock).Scan(&got); err != nil || got != 1 {
				t.Fatal(err)
			}
			if err = conn.Close(); err != nil {
				t.Fatal(err)
			}
		}
		target := ""
		switch fault {
		case "enable_alter":
			target = refs[0].SQL
		case "enable_insert", "disable_insert":
			target = refs[1].SQL
		case "enable_update", "disable_update":
			target = refs[2].SQL
		case "enable_check", "disable_column":
			target = refs[3].SQL
		case "enable_backfill":
			target = "UPDATE " + qt + " SET " + quoted + "=" + quoted + " WHERE id IN (" + strings.TrimSuffix(strings.Repeat("?,", 256), ",") + ") AND `record_text_key_" + strings.ReplaceAll(field.ID.String(), "-", "") + "` IS NULL AND " + quoted + " IS NOT NULL"
		}
		if target != "" {
			var observed atomic.Bool
			prefix := fault == "enable_backfill"
			if prefix {
				target = strings.SplitN(target, "?", 2)[0]
			}
			faultDB := physicalFaultDBMatching(t, database, target, &observed, policy.Principal.User, "isolated-text-only", prefix)
			faulty, err := store.NewPhysicalExecutor(faultDB, database, tenantID)
			if err != nil {
				t.Fatal(err)
			}
			if err = faulty.ExecuteSteps(ctx, tableID, operation); err == nil || !observed.Load() {
				t.Fatal("fault not observed", err)
			}
			if err = faultDB.Close(); err != nil {
				t.Fatal(err)
			}
			waitReleased()
			if fault == "enable_backfill" {
				var count int
				if err := db.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+qt+" WHERE `record_text_key_"+strings.ReplaceAll(field.ID.String(), "-", "")+"` IS NOT NULL").Scan(&count); err != nil || count <= 0 || count >= 300 {
					t.Fatal("expected committed partial batch", count, err)
				}
			}
		}
		if fault == "enable_canceled" {
			canceled, cancel := context.WithCancel(ctx)
			cancel()
			if err := executor.ExecuteSteps(canceled, tableID, operation); !errors.Is(err, context.Canceled) {
				t.Fatal(err)
			}
		}
		if err := executor.ExecuteSteps(ctx, tableID, operation); err != nil {
			t.Fatal("healthy resume", err)
		}
		if err := executor.ExecuteSteps(ctx, tableID, operation); err != nil {
			t.Fatal("execution replay", err)
		}
		if err := login.Close(); err != nil {
			t.Fatal(err)
		}
		exec("ALTER USER " + account + " ACCOUNT LOCK")
		if policy.TextGuards {
			exec("REVOKE SET_ANY_DEFINER ON *.* FROM " + account)
		}
		if policy.BackfillColumn != "" {
			exec("REVOKE UPDATE (" + quoted + ") ON " + qt + " FROM " + account)
		}
		verifier, err := store.NewPhysicalExecutor(db, database, tenantID)
		if err != nil {
			t.Fatal(err)
		}
		verifier, err = verifier.WithCreationReadiness(shared, policy)
		if err != nil {
			t.Fatal(err)
		}
		publication, err := store.NewPublicationStore(db, database, 1000, 1000, 1<<20)
		if err != nil {
			t.Fatal(err)
		}
		request := store.PhysicalPublicationRequest{TableID: tableID, Operation: store.PublicationOperation{ID: operation, RequestHash: hash, Condition: store.PublicationCondition{Mode: store.PublicationExactVersion, Version: expected}}, ActorKind: "api", ActorID: actor}
		calls := 0
		owner := func(tx *sql.Tx) error {
			calls++
			_, err := tx.ExecContext(ctx, "UPDATE "+schema+".data_model_fields SET is_unique=? WHERE tenant_id=? AND id=?", enable, mysqlstore.UUID(tenantID), mysqlstore.UUID(field.ID))
			return err
		}
		authorize := func(context.Context, uuid.UUID, store.PhysicalPublicationRequest) error { return nil }
		selected := verifier
		var observed atomic.Bool
		if strings.HasSuffix(fault, "_commit") {
			faulty, err := store.NewPhysicalExecutor(deliveryFaultDB(t, database, &observed), database, tenantID)
			if err != nil {
				t.Fatal(err)
			}
			selected, err = faulty.WithCreationReadiness(shared, policy)
			if err != nil {
				t.Fatal(err)
			}
		}
		result, err := selected.PublishVerifiedOperation(ctx, publication, request, policies, authorize, owner)
		if strings.HasSuffix(fault, "_commit") {
			var uncertain *mysqlstore.CommitError
			if !errors.As(err, &uncertain) || !observed.Load() {
				t.Fatal("expected uncertain publication", err)
			}
			waitReleased()
			result, err = verifier.PublishVerifiedOperation(ctx, publication, request, policies, authorize, owner)
		}
		if err != nil || result.Version == uuid.Nil || calls != 1 {
			t.Fatal("publication", err, calls)
		}
		var count int
		if err := db.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+qt).Scan(&count); err != nil || count != 302 {
			t.Fatal("records changed", count, err)
		}
		if enable {
			if err := db.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+qt+" WHERE `record_text_key_"+strings.ReplaceAll(field.ID.String(), "-", "")+"` IS NOT NULL").Scan(&count); err != nil || count != 300 {
				t.Fatal("backfill incomplete", count, err)
			}
		}
		for i := range mapped {
			if mapped[i].Field.ID == field.ID {
				mapped[i].Field.IsUnique = enable
			}
		}
		return plan
	}
	fault := strings.TrimPrefix(scenario, "service_allocated_native_text_patch_")
	if strings.HasPrefix(fault, "disable_") {
		previous = apply(true, "")
		previous = apply(false, fault)
	} else {
		previous = apply(true, fault)
	}
}

func TestTextPreparationCancellationAndDuplicateRollback(t *testing.T) {
	db, database := metadataDB(t)
	ctx := context.Background()
	schema, _ := mysqlstore.Identifier(database)
	table := "tenant_text_preflight"
	qt := schema + ".`" + table + "`"
	if _, err := db.ExecContext(ctx, "CREATE TABLE "+qt+" (id BINARY(16) PRIMARY KEY,value LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NULL)"); err != nil {
		t.Fatal(err)
	}
	long := strings.Repeat("x", 40000)
	for i, value := range []any{long + "a", long + "b", nil, nil, "Case", "case", "case ", ""} {
		if _, err := db.ExecContext(ctx, "INSERT INTO "+qt+" VALUES (?,?)", mysqlstore.UUID(uuid.New()), value); err != nil {
			t.Fatal(i, err)
		}
	}
	check := func(tx *sql.Tx) error { return store.CheckTextDuplicates(ctx, tx, database, table, "value") }
	if err := store.PreparePhysicalFieldChange(ctx, db, check); err != nil {
		t.Fatal("distinct long values rejected", err)
	}
	// Deterministic IDs put an equal value in a later 256-row batch.
	var rows []string
	var args []any
	for n := 1; n <= 601; n++ {
		var rowID uuid.UUID
		rowID[14] = byte(n >> 8)
		rowID[15] = byte(n)
		value := fmt.Sprintf("batch_%d", n)
		if n == 601 {
			value = "batch_1"
		}
		rows = append(rows, "(?,?)")
		args = append(args, mysqlstore.UUID(rowID), value)
	}
	if _, err := db.ExecContext(ctx, "INSERT INTO "+qt+" VALUES "+strings.Join(rows, ","), args...); err != nil {
		t.Fatal(err)
	}
	if err := store.PreparePhysicalFieldChange(ctx, db, check); !errors.Is(err, store.ErrPhysicalTextDuplicate) {
		t.Fatal("cross-batch duplicate missed", err)
	}
	var duplicateID uuid.UUID
	duplicateID[14] = byte(601 >> 8)
	duplicateID[15] = byte(601 & 255)
	if _, err := db.ExecContext(ctx, "DELETE FROM "+qt+" WHERE id=?", mysqlstore.UUID(duplicateID)); err != nil {
		t.Fatal(err)
	}
	id := uuid.New()
	if _, err := db.ExecContext(ctx, "INSERT INTO "+qt+" VALUES (?,?)", mysqlstore.UUID(id), long+"a"); err != nil {
		t.Fatal(err)
	}
	if err := store.PreparePhysicalFieldChange(ctx, db, check); !errors.Is(err, store.ErrPhysicalTextDuplicate) {
		t.Fatal("duplicate not rejected", err)
	}
	if _, err := db.ExecContext(ctx, "DELETE FROM "+qt+" WHERE id=?", mysqlstore.UUID(id)); err != nil {
		t.Fatal(err)
	}
	canceled, cancel := context.WithCancel(ctx)
	var oldConnection int64
	err := store.PreparePhysicalFieldChange(canceled, db, func(tx *sql.Tx) error {
		if err := tx.QueryRowContext(canceled, "SELECT CONNECTION_ID()").Scan(&oldConnection); err != nil {
			return err
		}
		if _, err := tx.ExecContext(canceled, "CREATE TEMPORARY TABLE dm_text_seen(id INT)"); err != nil {
			return err
		}
		if _, err := tx.ExecContext(canceled, "INSERT INTO "+qt+" VALUES (?,?)", mysqlstore.UUID(id), "must roll back"); err != nil {
			return err
		}
		cancel()
		return context.Canceled
	})
	if !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	var count int
	if err := db.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+qt+" WHERE id=?", mysqlstore.UUID(id)).Scan(&count); err != nil || count != 0 {
		t.Fatal("canceled mutation survived", err, count)
	}
	if err := store.PreparePhysicalFieldChange(ctx, db, func(tx *sql.Tx) error {
		var next int64
		if err := tx.QueryRowContext(ctx, "SELECT CONNECTION_ID()").Scan(&next); err != nil {
			return err
		}
		if next == oldConnection {
			return errors.New("canceled preparation connection reused")
		}
		return check(tx)
	}); err != nil {
		t.Fatal("retry after cancellation", err)
	}
}
