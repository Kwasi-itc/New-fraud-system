func TestPhysicalTableCreationReference(t *testing.T) {
	for _, collision := range []bool{false, true} {
		t.Run(fmt.Sprintf("forced_collision_%v", collision), func(t *testing.T) {
			db, database := metadataDB(t)
			ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
			defer cancel()
			schema, _ := mysqlstore.Identifier(database)
			exec := func(q string, args ...any) {
				t.Helper()
				if _, err := db.ExecContext(ctx, q, args...); err != nil {
					t.Fatal(err)
				}
			}
			if collision {
				// This database is generated by metadataDB and contains no application data.
				exec("DROP FUNCTION " + schema + ".data_model_exact_key_digest")
				exec("CREATE FUNCTION " + schema + ".data_model_exact_key_digest(p_value LONGBLOB) RETURNS BINARY(32) DETERMINISTIC NO SQL RETURN UNHEX(REPEAT('00',32))")
			}
			guard := installation.Definer{User: "rg_" + strings.ReplaceAll(uuid.NewString(), "-", "")[:24], Host: "%"}
			account, _ := guard.SQLAccount()
			create, _ := installation.CreateDefiner(guard)
			exec(create)
			t.Cleanup(func() {
				if _, err := db.Exec("DROP USER " + account); err != nil {
					t.Error(err)
				}
			})
			tenantID := uuid.New()
			var targets, objects, updates []string
			var policies []installation.AccountPolicy
			for i := 0; i < 2; i++ {
				tableID, objectID, updatedID := uuid.New(), uuid.New(), uuid.New()
				compact := func(id uuid.UUID) string { return strings.ReplaceAll(id.String(), "-", "") }
				tableName := "tenant_fixture_records_" + compact(tableID)
				objectName, updatedName := "field_object_id_"+compact(objectID)+"_value", "field_updated_at_"+compact(updatedID)+"_value"
				fields := []store.MappedPhysicalField{
					{Field: datamodel.Field{ID: objectID, TenantID: tenantID, TableID: tableID, Name: "object_id", DataType: datamodel.DataTypeString, IsUnique: true}, Components: []store.PhysicalField{{FieldID: objectID, Name: objectName, Component: "value"}}},
					{Field: datamodel.Field{ID: updatedID, TenantID: tenantID, TableID: tableID, Name: "updated_at", DataType: datamodel.DataTypeTimestamp}, Components: []store.PhysicalField{{FieldID: updatedID, Name: updatedName, Component: "value"}}},
				}
				planner, err := store.NewPhysicalPlanner(database, tenantID, store.PhysicalTable{TableID: tableID, Name: tableName}, fields)
				if err != nil {
					t.Fatal(err)
				}
				creation, err := planner.CreateTableReference(objectID, updatedID, guard)
				if err != nil {
					t.Fatal(err)
				}
				steps := creation.ReferenceSteps()
				// Capture reference definitions only. Production v1 execution rejects triggers.
				conn, err := db.Conn(ctx)
				if err != nil {
					t.Fatal(err)
				}
				for n := range steps {
					step := &steps[n]
					step.Before, err = migrations.Definition(ctx, conn, database, step.Kind, step.Name)
					if err != nil || step.Before != "" {
						t.Fatal("reference object already exists", err)
					}
					if _, err = conn.ExecContext(ctx, step.SQL); err != nil {
						t.Fatal(err)
					}
					step.After, err = migrations.Definition(ctx, conn, database, step.Kind, step.Name)
					if err != nil || step.After == "" {
						t.Fatal("missing reference definition", err)
					}
				}
				if err := conn.Close(); err != nil {
					t.Fatal(err)
				}
				if err := (migrations.Plan{Database: database, Steps: steps}).Validate(); err != nil {
					t.Fatal(err)
				}
				policies = append(policies, creation.DefinerPolicy())
				targets = append(targets, schema+".`"+tableName+"`")
				objects = append(objects, "`"+objectName+"`")
				updates = append(updates, "`"+updatedName+"`")
			}
			policy := policies[0]
			policy.Objects = append(policy.Objects, policies[1].Objects[0])
			grants, err := installation.GrantStatements(database, policy)
			if err != nil {
				t.Fatal(err)
			}
			for _, g := range grants {
				exec(g)
			}
			conn, err := db.Conn(ctx)
			if err != nil {
				t.Fatal(err)
			}
			if err := installation.VerifyAccountPolicy(ctx, conn, database, policy); err != nil {
				t.Fatal(err)
			}
			if err := conn.Close(); err != nil {
				t.Fatal(err)
			}
			writer := installation.Definer{User: "rw_" + strings.ReplaceAll(uuid.NewString(), "-", "")[:24], Host: "%"}
			writerAccount, _ := writer.SQLAccount()
			exec("CREATE USER " + writerAccount + " IDENTIFIED BY 'isolated-record-writer'")
			t.Cleanup(func() {
				if _, err := db.Exec("DROP USER " + writerAccount); err != nil {
					t.Error(err)
				}
			})
			for _, target := range targets {
				exec("GRANT SELECT,INSERT,UPDATE ON " + target + " TO " + writerAccount)
			}
			writerDB, err := mysqlstore.Open(ctx, mysqlstore.Config{Address: os.Getenv("DATA_MODEL_MYSQL_TEST_ADDRESS"), Database: database, User: writer.User, Password: "isolated-record-writer", AllowInsecureTransport: true, MaxOpen: 4, MaxIdle: 4, ConnectTimeout: 5 * time.Second, ReadTimeout: 10 * time.Second, WriteTimeout: 10 * time.Second, ConnMaxLifetime: time.Minute, ConnMaxIdleTime: time.Minute})
			if err != nil {
				t.Fatal(err)
			}
			defer writerDB.Close()
			insert := func(i int) string {
				return "INSERT INTO " + targets[i] + "(id," + objects[i] + "," + updates[i] + ",record_object_key_id) VALUES (?,?,?,?)"
			}
			at := mysqlstore.DateTime{Time: time.Now().UTC().Truncate(time.Microsecond)}
			values := []string{"", "a", "A", "a ", "é", "e\u0301", "a\x00", strings.Repeat("long-", 2000)}
			var ids []uuid.UUID
			for _, value := range values {
				id := uuid.New()
				ids = append(ids, id)
				if _, err := writerDB.ExecContext(ctx, insert(0), mysqlstore.UUID(id), value, at, mysqlstore.UUID(uuid.New())); err != nil {
					t.Fatal(err)
				}
				_, err := writerDB.ExecContext(ctx, insert(0), mysqlstore.UUID(uuid.New()), value, at, mysqlstore.UUID(uuid.New()))
				mysqlError(t, err, 1062)
			}
			// Same tenant, different table: fixed-width scopes must not share key IDs.
			if _, err := writerDB.ExecContext(ctx, insert(1), mysqlstore.UUID(uuid.New()), "a", at, nil); err != nil {
				t.Fatal(err)
			}
			var equal int
			if err := db.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+targets[0]+" a JOIN "+targets[1]+" b ON a.record_object_key_id=b.record_object_key_id").Scan(&equal); err != nil || equal != 0 {
				t.Fatal("scope collision", equal, err)
			}
			var expiry sql.NullTime
			var start time.Time
			if err := writerDB.QueryRowContext(ctx, "SELECT valid_from,valid_until FROM "+targets[0]+" WHERE id=?", mysqlstore.UUID(ids[0])).Scan(&start, &expiry); err != nil || start.IsZero() || expiry.Valid {
				t.Fatal("temporal envelope", err)
			}
			_, err = writerDB.ExecContext(ctx, "UPDATE "+targets[0]+" SET "+objects[0]+"=?,record_object_key_id=? WHERE id=?", "a", mysqlstore.UUID(uuid.New()), mysqlstore.UUID(ids[0]))
			mysqlError(t, err, 1062)
			// A caller cannot substitute a key belonging to a different raw value.
			if _, err := writerDB.ExecContext(ctx, "UPDATE "+targets[0]+" SET record_object_key_id=? WHERE id=?", mysqlstore.UUID(uuid.New()), mysqlstore.UUID(ids[1])); err != nil {
				t.Fatal(err)
			}
			var value string
			if err := db.QueryRowContext(ctx, "SELECT k.raw_value FROM "+targets[0]+" r JOIN "+schema+".data_model_exact_keys k ON k.id=r.record_object_key_id WHERE r.id=?", mysqlstore.UUID(ids[1])).Scan(&value); err != nil || value != "a" {
				t.Fatal("forged key survived", value, err)
			}
			// Allocation is part of the caller transaction and rolls back with it.
			tx, err := writerDB.BeginTx(ctx, nil)
			if err != nil {
				t.Fatal(err)
			}
			if _, err := tx.ExecContext(ctx, insert(0), mysqlstore.UUID(uuid.New()), "rollback-only", at, nil); err != nil {
				t.Fatal(err)
			}
			if err := tx.Rollback(); err != nil {
				t.Fatal(err)
			}
			var count int
			if err := db.QueryRowContext(ctx, "SELECT COUNT(*) FROM data_model_exact_keys WHERE raw_value=?", []byte("rollback-only")).Scan(&count); err != nil || count != 0 {
				t.Fatal("allocation leaked", count, err)
			}
			// Competing requests for the same raw value cannot allocate distinct keys.
			results := make(chan error, 2)
			for i := 0; i < 2; i++ {
				go func() {
					_, err := writerDB.ExecContext(ctx, insert(0), mysqlstore.UUID(uuid.New()), "concurrent", at, nil)
					results <- err
				}()
			}
			a, b := <-results, <-results
			if a == nil {
				mysqlError(t, b, 1062)
			} else if b == nil {
				mysqlError(t, a, 1062)
			} else {
				t.Fatal(a, b)
			}
			for _, q := range []string{"SELECT * FROM data_model_exact_keys", "CALL data_model_resolve_exact_key(_binary'record_object_id',X'',_binary'bypass',@k)", "ALTER TABLE " + targets[0] + " DROP COLUMN record_object_key_id"} {
				if _, err := writerDB.ExecContext(ctx, q); err == nil {
					t.Fatal("writer bypass accepted", q)
				}
			}
			conn, err = writerDB.Conn(ctx)
			if err != nil {
				t.Fatal(err)
			}
			defer conn.Close()
			for _, setting := range []string{"unique_checks", "foreign_key_checks"} {
				if _, err := conn.ExecContext(ctx, "SET SESSION "+setting+"=0"); err != nil {
					t.Fatal(err)
				}
				_, err := conn.ExecContext(ctx, insert(0), mysqlstore.UUID(uuid.New()), "unsafe", at, nil)
				mysqlError(t, err, 1644)
				if _, err := conn.ExecContext(ctx, "SET SESSION "+setting+"=1"); err != nil {
					t.Fatal(err)
				}
			}
		})
	}
}
