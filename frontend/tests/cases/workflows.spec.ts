  await page.screenshot({ path: "test-results/workflow-nested-mobile.png", fullPage: true });
  await nested.getByLabel("Condition type").last().selectOption("always");
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(nested.getByLabel("Condition type").last()).toHaveValue("never");
