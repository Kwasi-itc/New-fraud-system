import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";

test("published internal records reach the existing results, enrichment and history UI", async ({ page, context }) => {
  test.skip(!process.env.CONTROLLED_BROWSER_STATE_FILE, "Requires the isolated Go API/worker browser handshake");
  const state = JSON.parse(readFileSync(process.env.CONTROLLED_BROWSER_STATE_FILE!, "utf8"));
  await context.addCookies([{ name: "case_test_session", value: "fixture-analyst", domain: "127.0.0.1", path: "/", httpOnly: true, sameSite: "Lax" }]);
  await page.goto("/screening-search");
  await page.getByLabel("Screening provider").selectOption("internal-watchlists");
  await page.getByRole("checkbox", { name: /Controlled private-controlled/ }).check();
  await page.getByLabel("Name", { exact: true }).fill("Ama Fixture Alias");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Ama Testperson", exact: true })).toBeVisible({ timeout: 20000 });
  await expect(page.getByText("Exact name match", { exact: true })).toBeVisible();
  await page.getByText("Candidate details", { exact: true }).click();
  await expect(page.getByText(state.generation, { exact: true })).toBeVisible();
  await expect(page.getByText("Controlled fictional fixture; not an official designation", { exact: true })).toBeVisible();
  await expect(page.getByText("exact-name-v1", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Monitor updates", exact: true }).click();
  await expect(page.getByText(/Monitoring active/)).toBeVisible();
  await expect(page.getByText("Latest screening uses the current dataset versions.", { exact: true })).toBeVisible({timeout:20000});
  await page.getByRole("button", { name: "Pause monitoring", exact: true }).click();
  await expect(page.getByText(/Monitoring paused/)).toBeVisible();
  await page.getByRole("button", { name: "Load source details", exact: true }).click();
  await expect(page.getByRole("button", { name: "Source details loaded", exact: true })).toBeVisible();
  if (process.env.CONTROLLED_UI_SCREENSHOT) await page.screenshot({ path: process.env.CONTROLLED_UI_SCREENSHOT, fullPage: true });
  await page.getByRole("region", { name: "Search history" }).getByRole("button", { name: /Ama Fixture Alias/ }).first().click();
  await expect(page.getByText(/Stored search results/)).toBeVisible();
  await expect(page.getByRole("heading", { name: "Ama Testperson", exact: true })).toBeVisible();
  await page.getByLabel("Entity type").selectOption("Organization");
  await page.getByLabel("Name", { exact: true }).fill("Fixture Payments");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Example Fixture Payments Ltd", exact: true })).toBeVisible({ timeout: 20000 });
  await expect(page.getByRole("link", { name: "View printable report" })).toBeVisible();
  await page.getByLabel("Matching method").selectOption("name-fuzzy-v1");
  await page.getByLabel("Entity type").selectOption("Person");
  await page.getByLabel("Name", { exact: true }).fill("Ama Testpreson");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Ama Testperson", exact: true })).toBeVisible({ timeout: 20000 });
  await page.getByText("Candidate details", { exact: true }).click();
  await expect(page.getByText("name-fuzzy-v1", { exact: true })).toBeVisible();
  await expect(page.getByText("edit_similarity", { exact: true })).toBeVisible();
  expect(state.case_id).toBeTruthy();
  const enriched = await context.request.post(`/api/case-screening-enrichment/${state.tenant}/${state.case_id}/${state.match_id}`, { headers: { origin: "http://127.0.0.1:3100" }, data: {} });
  expect(enriched.status()).toBe(200);
  expect(await enriched.json()).toEqual({ enriched: true });
  if (process.env.CONTROLLED_UI_SCREENSHOT) await page.screenshot({ path: process.env.CONTROLLED_UI_SCREENSHOT, fullPage: true });
});
